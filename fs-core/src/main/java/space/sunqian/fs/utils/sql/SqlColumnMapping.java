package space.sunqian.fs.utils.sql;

import space.sunqian.annotation.Immutable;
import space.sunqian.annotation.Nonnull;
import space.sunqian.fs.object.meta.PropertyMeta;

/**
 * Represents a mapping from a Java bean property to a SQL column.
 *
 * @author sunqian
 */
@Immutable
public interface SqlColumnMapping {

    /**
     * Returns the bean mapping that owns this column mapping.
     *
     * @return the bean mapping that owns this column mapping
     */
    @Nonnull
    SqlBeanMapping owner();

    /**
     * Returns the name of this SQL column.
     *
     * @return the name of this SQL column
     */
    @Nonnull
    String columnName();

    /**
     * Returns the name of the bean property mapped to this SQL column.
     *
     * @return the name of the bean property mapped to this SQL column
     */
    default @Nonnull String propertyName() {
        return propertyMeta().name();
    }

    /**
     * Returns whether this SQL column is the primary key.
     *
     * @return {@code true} if this SQL column is the primary key, {@code false} otherwise
     */
    boolean isPrimaryKey();

    /**
     * Returns whether this SQL column is auto-generated.
     *
     * @return {@code true} if this SQL column is auto-generated, {@code false} otherwise
     */
    boolean isAutoGenerated();

    /**
     * Returns the metadata of the property mapped to this SQL column.
     *
     * @return the metadata of the property mapped to this SQL column
     */
    @Nonnull
    PropertyMeta propertyMeta();
}
