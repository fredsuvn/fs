package space.sunqian.fs.utils.sql;

import space.sunqian.annotation.Immutable;
import space.sunqian.annotation.Nonnull;
import space.sunqian.annotation.Nullable;
import space.sunqian.fs.Fs;
import space.sunqian.fs.base.string.NameFormatter;
import space.sunqian.fs.base.string.NameMapper;
import space.sunqian.fs.base.string.StringKit;
import space.sunqian.fs.cache.SimpleCache;
import space.sunqian.fs.object.meta.ObjectMeta;
import space.sunqian.fs.object.meta.PropertyMeta;
import space.sunqian.fs.reflect.TypeKit;
import space.sunqian.fs.utils.sql.annotation.SqlColumn;
import space.sunqian.fs.utils.sql.annotation.SqlTable;

import java.lang.reflect.Type;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.Map;

final class SqlMapperBack {

    static @Nonnull SqlMapper defaultMapper() {
        return SqlMapperImpl.INST;
    }

    static @Nonnull NameMapper defaultToColumnName() {
        return NameMappers.TO_COLUMN_NAME_MAPPER;
    }

    static @Nonnull NameMapper defaultToPropertyName() {
        return NameMappers.TO_PROPERTY_NAME_MAPPER;
    }

    static @Nonnull NameMapper defaultToTableName() {
        return NameMappers.TO_TABLE_NAME_MAPPER;
    }

    private enum SqlMapperImpl implements SqlMapper {

        INST;

        private static final @Nonnull SimpleCache<@Nonnull ObjectMeta, @Nonnull SqlBeanMapping> CACHE =
            SimpleCache.ofSoft();

        static {
            Fs.registerGlobalCache(CACHE);
        }

        @Override
        public @Nonnull SqlBeanMapping toBeanMapping(@Nonnull ObjectMeta beanMeta) {
            return CACHE.get(beanMeta, this::toBeanMapping0);
        }

        private @Nonnull SqlBeanMapping toBeanMapping0(@Nonnull ObjectMeta beanMeta) {
            return new SqlBeanMappingImpl(beanMeta);
        }

        private static final class SqlBeanMappingImpl implements SqlBeanMapping {

            private final @Nullable String sourceName;
            private final @Immutable
            @Nonnull Map<@Nonnull String, @Nonnull SqlColumnMapping> columnsByColumnName;
            private final @Immutable
            @Nonnull Map<@Nonnull String, @Nonnull SqlColumnMapping> columnsByPropertyName;
            private final @Nullable SqlColumnMapping primaryKey;
            private final @Nonnull ObjectMeta beanMeta;

            private SqlBeanMappingImpl(@Nonnull ObjectMeta beanMeta) {
                Type tableType = beanMeta.type();

                // table name
                {
                    SqlTable sqlTable = beanMeta.annotations().annotation(SqlTable.class);
                    this.sourceName = toTableNameMapper(sqlTable, tableType);
                }

                // columns
                {
                    Map<String, SqlColumnMapping> columnsByColumnName = new LinkedHashMap<>();
                    Map<String, SqlColumnMapping> columnsByPropertyName = new LinkedHashMap<>();
                    SqlColumnMapping primaryKey = null;
                    for (PropertyMeta propertyMeta : beanMeta.properties().values()) {
                        SqlColumn sqlColumn = propertyMeta.annotations().annotation(SqlColumn.class);
                        if (sqlColumn == null) {
                            continue;
                        }
                        String propertyName = propertyMeta.name();
                        String columnName = sqlColumn.value().isEmpty() ?
                            SqlMapper.defaultToColumnName().map(propertyName) : sqlColumn.value();
                        boolean isPrimaryKey = sqlColumn.primary();
                        boolean isAutoGenerated = sqlColumn.autoGenerated();
                        SqlColumnMapping columnMapping = new SqlColumnMappingImpl(
                            columnName,
                            isPrimaryKey,
                            isAutoGenerated,
                            propertyMeta
                        );
                        columnsByColumnName.put(columnName, columnMapping);
                        columnsByPropertyName.put(propertyName, columnMapping);
                        // primary key
                        if (primaryKey == null && isPrimaryKey) {
                            primaryKey = columnMapping;
                        }
                    }
                    this.columnsByColumnName = Collections.unmodifiableMap(columnsByColumnName);
                    this.columnsByPropertyName = Collections.unmodifiableMap(columnsByPropertyName);
                    this.primaryKey = primaryKey;
                }

                // set bean meta
                {
                    this.beanMeta = beanMeta;
                }
            }

            private @Nonnull String toTableNameMapper(@Nullable SqlTable sqlTable, @Nonnull Type tableType) {
                if (sqlTable != null) {
                    String value = sqlTable.value();
                    if (!value.isEmpty()) {
                        return value;
                    }
                }
                return SqlMapper.defaultToTableName().map(tableType.getTypeName());
            }

            @Override
            public @Nullable String sourceName() {
                return sourceName;
            }

            @Override
            public @Nonnull Map<@Nonnull String, @Nonnull SqlColumnMapping> columnsByColumnName() {
                return columnsByColumnName;
            }

            @Override
            public @Nonnull Map<@Nonnull String, @Nonnull SqlColumnMapping> columnsByPropertyName() {
                return columnsByPropertyName;
            }

            @Override
            public @Nullable SqlColumnMapping primaryKey() {
                return primaryKey;
            }

            @Override
            public @Nonnull ObjectMeta beanMeta() {
                return beanMeta;
            }

            private final class SqlColumnMappingImpl implements SqlColumnMapping {

                private final @Nonnull String columnName;
                private final boolean isPrimaryKey;
                private final boolean isAutoGenerated;
                private final @Nonnull PropertyMeta propertyMeta;

                private SqlColumnMappingImpl(
                    @Nonnull String columnName,
                    boolean isPrimaryKey,
                    boolean isAutoGenerated,
                    @Nonnull PropertyMeta propertyMeta
                ) {
                    this.columnName = columnName;
                    this.isPrimaryKey = isPrimaryKey;
                    this.isAutoGenerated = isAutoGenerated;
                    this.propertyMeta = propertyMeta;
                }

                @Override
                public @Nonnull SqlBeanMapping owner() {
                    return SqlBeanMappingImpl.this;
                }

                @Override
                public @Nonnull String columnName() {
                    return columnName;
                }

                @Override
                public boolean isPrimaryKey() {
                    return isPrimaryKey;
                }

                @Override
                public boolean isAutoGenerated() {
                    return isAutoGenerated;
                }

                @Override
                public @Nonnull PropertyMeta propertyMeta() {
                    return propertyMeta;
                }
            }
        }
    }

    private static final class NameMappers {

        private static final @Nonnull NameFormatter LOWER_CAMEL = NameFormatter.lowerCamel();
        private static final @Nonnull NameFormatter UPPER_CAMEL = NameFormatter.upperCamel();
        private static final @Nonnull NameFormatter UNDERSCORE = NameFormatter.delimiter("_");

        private static final @Nonnull NameMapper TO_COLUMN_NAME_MAPPER = propertyName ->
            StringKit.upperCase(LOWER_CAMEL.format(propertyName, UNDERSCORE));

        private static final @Nonnull NameMapper TO_PROPERTY_NAME_MAPPER = columnName ->
            UNDERSCORE.format(StringKit.lowerCase(columnName), LOWER_CAMEL);

        private static final @Nonnull NameMapper TO_TABLE_NAME_MAPPER = javaTypeName ->
            StringKit.upperCase(UPPER_CAMEL.format(TypeKit.getLastName(javaTypeName, true), UNDERSCORE));

        private NameMappers() {
        }
    }

    private SqlMapperBack() {
    }
}
