package space.sunqian.fs.utils.sql;

import space.sunqian.annotation.Immutable;
import space.sunqian.annotation.Nonnull;
import space.sunqian.fs.object.meta.PropertyMeta;

/**
 * Represents a mapping from a Java bean property to a column of a SQL table, view, or query result set.
 *
 * @author sunqian
 */
@Immutable
public interface SqlPropertyMapping {

    /**
     * Returns the bean mapping that owns this property mapping.
     *
     * @return the bean mapping that owns this property mapping
     */
    @Nonnull
    SqlBeanMapping owner();

    /**
     * Returns the name of the SQL column mapped to this property mapping.
     *
     * @return the name of the SQL column mapped to this property mapping
     */
    @Nonnull
    String columnName();

    /**
     * Returns whether the SQL column mapped to this property mapping is the primary key.
     *
     * @return {@code true} if the SQL column is the primary key, {@code false} otherwise
     */
    boolean isPrimaryKey();

    /**
     * Returns whether the SQL column mapped to this property mapping is auto-generated.
     *
     * @return {@code true} if the SQL column is auto-generated, {@code false} otherwise
     */
    boolean isAutoGenerated();

    /**
     * Returns the type of the mapped property.
     *
     * @return the type of the mapped property
     */
    @Nonnull
    PropertyMeta propertyType();
}
