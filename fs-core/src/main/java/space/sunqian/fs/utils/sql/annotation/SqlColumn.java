package space.sunqian.fs.utils.sql.annotation;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Marks a Java bean property that can be mapped to a SQL column.
 * <p>
 * The following example marks a property to be mapped to a SQL column "CREATED_BY":
 * <pre>{@code
 * @SqlColumn("CREATED_BY")
 * private String createdBy;
 * }</pre>
 * <p>
 * It can be used on getters, setters, and backing fields. When reading this annotation from a bean property, it should
 * be retrieved in this order:
 * <ol>
 *     <li>Getter method.
 *     <li>Setter method.
 *     <li>Backing field.
 * </ol>
 *
 * @author sunqian
 */
@Documented
@Retention(RetentionPolicy.RUNTIME)
@Target({
    ElementType.METHOD,
    ElementType.FIELD,
})
public @interface SqlColumn {

    /**
     * The column name to be mapped.
     * <p>
     * The default is empty, which means the column name is derived from the default naming policy.
     *
     * @return the column name to be mapped
     */
    String value() default "";

    /**
     * Tells whether this column is auto-generated by the database or not. The default is {@code false}.
     *
     * @return {@code true} if this column is auto-generated, {@code false} otherwise
     */
    boolean autoGenerated() default false;

    /**
     * Tells whether this column is the primary key of the table/view or not. The default is {@code false}.
     *
     * @return {@code true} if this column is the primary key, {@code false} otherwise
     */
    boolean primaryKey() default false;
}
