package space.sunqian.fs.utils.sql;

import space.sunqian.annotation.Immutable;
import space.sunqian.annotation.Nonnull;

/**
 * Describes the SQL column that a Java bean property is mapped to.
 *
 * @author sunqian
 */
@Immutable
public interface SqlColumnInfo {

    /**
     * Returns the column name.
     *
     * @return the column name
     */
    @Nonnull
    String name();

    /**
     * Returns whether the column is a primary key.
     *
     * @return {@code true} if the column is a primary key, {@code false} otherwise
     */
    boolean isPrimaryKey();

    /**
     * Returns whether the column is auto-generated.
     *
     * @return {@code true} if the column is auto-generated, {@code false} otherwise
     */
    boolean isAutoGenerated();
}
